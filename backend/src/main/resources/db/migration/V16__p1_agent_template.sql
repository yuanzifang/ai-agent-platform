-- P1 模板库（需求 3.24）：预置 Agent 模板，一键创建（租户自定义模板 P2）
CREATE TABLE IF NOT EXISTS agent_template (
    id BIGINT NOT NULL AUTO_INCREMENT,
    name VARCHAR(128) NOT NULL,
    description VARCHAR(512) NULL,
    category VARCHAR(64) NULL,
    icon_url VARCHAR(512) NULL,
    system_prompt TEXT NULL,
    opening_statement TEXT NULL,
    model_config JSON NULL,
    agent_capabilities JSON NULL,
    memory_config JSON NULL,
    variables JSON NULL,
    tools JSON NULL,
    skills JSON NULL,
    knowledge_bases JSON NULL,
    is_builtin TINYINT NOT NULL DEFAULT 0,
    tenant_id BIGINT NULL,
    created_by BIGINT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_agent_template_tenant (tenant_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

